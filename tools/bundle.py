#!/usr/bin/env python3
"""
tools/bundle.py — builds the single-file Cherry UI bundle.

The library ships as a Rojo project (one ModuleScript per file), but Roblox Lua
executors and single-script users cannot `require` a ModuleScript tree. This
script inlines every module into one chunk, rewriting the relative
`require(script...)` calls into a tiny in-memory module registry.

Usage:
    python3 tools/bundle.py                      # writes dist/CherryUI.lua
    python3 tools/bundle.py --out other.lua
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
VERSION_RE = re.compile(r'self\.Version\s*=\s*"([^"]+)"')
REQUIRE_RE = re.compile(r"require\(\s*(script(?:\s*\.\s*[A-Za-z_]\w*)+)\s*\)")


def module_node(rel: pathlib.Path) -> list[str]:
    """The instance path of a module, mirroring Rojo's init.lua rule."""
    parts = list(rel.with_suffix("").parts)
    if parts and parts[-1] == "init":
        parts = parts[:-1]
    return parts


def discover() -> dict[str, tuple[pathlib.Path, list[str]]]:
    modules = {}
    for path in sorted(SRC.rglob("*.lua")):
        rel = path.relative_to(SRC)
        modules[str(rel.with_suffix("")).replace("\\", "/")] = (path, module_node(rel))
    return modules


def resolve(modules, node: list[str]) -> str | None:
    key = "/".join(node)
    if key in modules:
        return key
    init_key = (key + "/init") if key else "init"
    if init_key in modules:
        return init_key
    return None


def rewrite(source: str, module_key: str, modules) -> tuple[str, list[str]]:
    owner_node = modules[module_key][1]
    missing: list[str] = []

    def replace(match: re.Match) -> str:
        expression = re.sub(r"\s+", "", match.group(1))
        tokens = expression.split(".")[1:]
        node = list(owner_node)

        for token in tokens:
            if token == "Parent":
                if not node:
                    missing.append(expression + " (walks above the root)")
                    return match.group(0)
                node.pop()
            else:
                node.append(token)

        target = resolve(modules, node)
        if target is None:
            missing.append(expression)
            return match.group(0)
        return f'__require("{target}")'

    return REQUIRE_RE.sub(replace, source), missing


def build(out_path: pathlib.Path, include_example: bool = False) -> int:
    modules = discover()
    if not modules:
        print(f"error: no Lua modules found in {SRC}", file=sys.stderr)
        return 1

    version = "0.0.0"
    init = modules.get("init")
    if init:
        match = VERSION_RE.search(init[0].read_text())
        if match:
            version = match.group(1)

    errors: list[str] = []
    bodies: list[tuple[str, str]] = []

    for key in sorted(modules):
        if key == "Example" and not include_example:
            continue
        source = modules[key][0].read_text()
        rewritten, missing = rewrite(source, key, modules)
        for item in missing:
            errors.append(f"{key}: unresolved require({item})")
        bodies.append((key, rewritten))

    if errors:
        for error in errors:
            print("error: " + error, file=sys.stderr)
        return 1

    out = []
    out.append("--[[")
    out.append(f"\tCherry UI {version} — single-file bundle.")
    out.append("")
    out.append("\tGenerated by tools/bundle.py from src/. Do not edit by hand;")
    out.append("\tchange the modular sources and rebuild.")
    out.append("")
    out.append("\tLoad it from a LocalScript or a Roblox Lua executor:")
    out.append("")
    out.append('\t\tlocal CherryUI = loadstring(game:HttpGet("<raw url>/dist/CherryUI.lua"))()')
    out.append("\t\tlocal window = CherryUI:CreateWindow({ Title = \"Cherry\" })")
    out.append("")
    out.append("\tThe chunk returns the library table (and sets `getgenv().CherryUI`")
    out.append("\twhen the environment provides `getgenv`).")
    out.append("]]")
    out.append("")
    out.append("local __modules = {}")
    out.append("local __cache = {}")
    out.append("")
    out.append("local function __require(name)")
    out.append("\tlocal cached = __cache[name]")
    out.append("\tif cached ~= nil then")
    out.append("\t\treturn cached")
    out.append("\tend")
    out.append("")
    out.append("\tlocal factory = __modules[name]")
    out.append("\tif not factory then")
    out.append('\t\terror("[CherryUI] missing module: " .. tostring(name))')
    out.append("\tend")
    out.append("")
    out.append("\tlocal value = factory()")
    out.append("\t__cache[name] = value")
    out.append("\treturn value")
    out.append("end")
    out.append("")

    for key, body in bodies:
        out.append(f'__modules["{key}"] = function()')
        for line in body.rstrip("\n").split("\n"):
            out.append(("\t" + line) if line.strip() else "")
        out.append("end")
        out.append("")

    out.append('local CherryUI = __require("init")')
    out.append("")
    out.append("-- Expose the library to executor environments so other scripts can do")
    out.append("-- `getgenv().CherryUI:CreateWindow(...)` without loading it twice.")
    out.append("if type(getgenv) == \"function\" then")
    out.append("\tpcall(function()")
    out.append("\t\tgetgenv().CherryUI = CherryUI")
    out.append("\tend)")
    out.append("end")
    out.append("")
    out.append("return CherryUI")
    out.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out))
    print(f"Bundled {len(bodies)} modules -> {out_path.relative_to(ROOT) if out_path.is_relative_to(ROOT) else out_path}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the single-file Cherry UI bundle.")
    parser.add_argument("--out", default="dist/CherryUI.lua", help="output path (default: dist/CherryUI.lua)")
    parser.add_argument("--include-example", action="store_true", help="also bundle src/Example.lua")
    args = parser.parse_args()

    out_path = pathlib.Path(args.out)
    if not out_path.is_absolute():
        out_path = ROOT / out_path

    return build(out_path, include_example=args.include_example)


if __name__ == "__main__":
    raise SystemExit(main())
